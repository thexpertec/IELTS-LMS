// ─── Table completion ─────────────────────────────────────────────────────────

function TableGroup({
  group,
  answers,
  setAnswer,
}: {
  group: QuestionGroup;
  answers: Record<number, string>;
  setAnswer: (num: number, val: string) => void;
}) {
  const cfg = group.tableConfig!;
  const qByNum = Object.fromEntries(group.questions.map((q) => [q.num, q]));

  return (
    <div className="overflow-x-auto">
      <table className="w-full text-xs border border-border">
        <thead>
          <tr className="bg-muted">
            {cfg.headers.map((h) => (
              <th key={h} className="text-left px-3 py-2 border-b border-border font-semibold">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {cfg.rows.map((row, rIdx) => {
            const qNum = row.blanks[0];
            const q = qByNum[qNum];
            return (
              <tr key={rIdx} className="border-b border-border last:border-0">
                <td className="px-3 py-2 text-muted-foreground align-top">{row.label}</td>
                <td className="px-3 py-2 align-top" id={`q-${qNum}`}>
                  <div className="flex items-center gap-1 flex-wrap text-foreground leading-6">
                    <span>{q.stem?.split("_____")[0]}</span>
                    <Input
                      className="inline-flex h-6 w-24 text-xs px-2 border-0 border-b border-border rounded-none bg-transparent focus-visible:ring-0 focus-visible:border-[hsl(var(--primary))]"
                      placeholder={`${qNum}`}
                      value={answers[qNum] || ""}
                      onChange={(e) => setAnswer(qNum, e.target.value)}
                      data-testid={`input-q${qNum}`}
                    />
                    <span>{q.stem?.split("_____")[1]}</span>
                  </div>
                </td>
              </tr>
            );
          })}
        </tbody>
      </table>
    </div>
  );
}

