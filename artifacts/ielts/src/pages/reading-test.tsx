// ─── QUESTION GROUP BLOCK ─────────────────────────────────────────────────────

function QuestionGroupBlock({
  group,
  answers,
  setAnswer,
}: {
  group: QuestionGroup;
  answers: Record<number, string>;
  setAnswer: (num: number, val: string) => void;
}) {
  return (
    <div id={`group-${group.id}`} className="space-y-4">
      <h3 className="text-sm font-bold text-foreground">{group.title}</h3>
      <div className="text-xs text-muted-foreground whitespace-pre-line leading-relaxed border-l-4 border-[hsl(var(--primary))] pl-3">
        {group.instructions}
      </div>

      {group.type === "fill" && (
        <FillGroup group={group} answers={answers} setAnswer={setAnswer} />
      )}
      {group.type === "tfng" && (
        <TFNGGroup group={group} answers={answers} setAnswer={setAnswer} />
      )}
      {group.type === "paragraph" && (
        <ParagraphGroup group={group} answers={answers} setAnswer={setAnswer} />
      )}
      {group.type === "table" && (
        <TableGroup group={group} answers={answers} setAnswer={setAnswer} />
      )}
      {group.type === "mcq" && (
        <MCQGroup group={group} answers={answers} setAnswer={setAnswer} />
      )}
    </div>
  );
}

